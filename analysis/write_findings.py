"""
Regenerate analysis/findings.md from computed outputs only:
  - analysis/outputs/metrics.json   (python analysis/run_analytics.py)
  - docs/benchmark_results_100k.json (python scripts/benchmark_optimizations.py, Postgres)

Nothing in findings.md is typed by hand, so it cannot drift from the pipeline.
tests/test_numbers.py fails if README.md quotes a number that disagrees.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main() -> None:
    m = json.loads((ROOT / "analysis" / "outputs" / "metrics.json").read_text(encoding="utf-8"))
    b = json.loads((ROOT / "docs" / "benchmark_results_100k.json").read_text(encoding="utf-8"))

    cats = "\n".join(f"| {k} | {v:.1f}% |" for k, v in m["category_revenue_share_pct"].items())
    segs = "\n".join(f"| {k} | ${v:,.0f} |" for k, v in m["revenue_per_customer_by_segment"].items())
    rfm = "\n".join(f"| {k} | {v:,} |" for k, v in m["rfm_segment_counts"].items())
    bench = "\n".join(
        f"| {r['num']} | {r['title']} | {r['before']['execution_ms_median']:.1f} | "
        f"{r['after']['execution_ms_median']:.1f} | {r['execution_change_pct']:+.1f}% | "
        f"{'yes' if r['same_result'] else 'no (different result by design)'} |"
        for r in b["results"])
    rows = b["table_rows"]

    text = f"""# Findings

> **Synthetic data.** Every number below is computed from generated data, not a real retailer.
> This file is generated by `python analysis/write_findings.py`; do not edit it by hand.

## Dataset (DuckDB pipeline, `analysis/run_analytics.py`, seed 42)

{m['customers']:,} customers, {m['orders']:,} orders, {m['order_items']:,} line items across {m['states']} states.
{m['cancelled_or_returned_pct']}% of orders are cancelled or returned and are excluded from revenue.
Net revenue = quantity x unit price x (1 - line discount).

## 1. Revenue concentration

The top 10% of customers ({max(1, int(m['customers_with_revenue'] * 0.10)):,} of {m['customers_with_revenue']:,} with
revenue) generate **{m['top10pct_revenue_share_pct']}%** of net revenue. The generator draws customers with Pareto
weights, so this concentration is built into the data: the pipeline measures it, it did not discover it.

## 2. Seasonality

Q4 (Oct-Dec) is **{m['q4_revenue_share_pct']}%** of revenue and Q1 is {m['q1_revenue_share_pct']}%, again following
the month weights in the generator.

## 3. Category mix

| Top-level category | Revenue share |
|---|---|
{cats}

Electronics dominates because laptop and phone prices are far higher than other categories. The pipeline's
products have no cost column, so it says **nothing about margins** (an earlier version of this file claimed
Electronics had the thinnest margins; that is not computed anywhere and was removed).

## 4. Order value

Mean order value ${m['aov_mean']:,.2f} vs median ${m['aov_median']:,.2f}: right-skewed, so report the median.

## 5. Customer segments

| Segment label | Net revenue per customer |
|---|---|
{segs}

Segment labels are assigned at random in the generator, independent of purchasing, so they do not separate
spend. (An earlier version claimed "VIP customers spend 3.2x more"; the data does not support that.)

## 6. RFM churn segments (customers with revenue)

| Segment | Customers |
|---|---|
{rfm}

## 7. Geography

{m['top_state_by_revenue']} is the largest state by revenue ({m['top_state_revenue_share_pct']}%). The generator only
uses 12 Southern states, so no claims are made about other regions.

## 8. Query optimization (PostgreSQL, measured)

`scripts/benchmark_optimizations.py` on {b['postgres'].split(',')[0]} with {rows['customers']:,} customers,
{rows['orders']:,} orders and {rows['order_items']:,} line items (seed data plus `scripts/generate_data.py
--customers 20000 --orders 100000`). Median of {b['iterations']} `EXPLAIN (ANALYZE)` runs after 2 warm-ups.

| # | Optimization | Before (ms) | After (ms) | Change | Same rows? |
|---|---|---|---|---|---|
{bench}

What this shows: replacing per-customer correlated subqueries with one aggregation pass (#1, #4) is a large,
real win. The covering index (#2) barely matters because the query aggregates most of `order_items` anyway.
The pre-filtering rewrites (#3, #5) return different rows than their originals and are slower on this data,
so they are not optimizations here.

## Not computed (removed)

Earlier versions of this file stated a supplier lead-time correlation (r = 0.74), a "laptops + USB-C hubs"
lift of 4.8, dead-stock and days-of-inventory figures, employee-team results, payment/shipping shares and
state rankings including CA/NY/IL. None of these are produced by any script in this repository, so they were
removed rather than kept as unverifiable claims. The 15 SQL queries in `queries/` can compute several of
them against a database; they are verified to run (CI) but their outputs on the 50-customer seed sample are
too small to support findings.
"""
    (ROOT / "analysis" / "findings.md").write_text(text, encoding="utf-8")
    print("wrote analysis/findings.md")


if __name__ == "__main__":
    main()
